/** @type {Record<string, Record<string, any>>} */
const DICTS = { ru, en };
let lang = 'ru';

/** @param {string} l */
export function setLanguage(l) {
  lang = DICTS[l] ? l : 'ru';
  document.documentElement.lang = lang;
}

export function language() {
  return lang;
}

export function defaultLanguage() {
  return navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

/** @param {string} key @param {...any} args @returns {string} */
export function t(key, ...args) {
  const v = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

/** Russian plural forms. @param {number} n @param {string} one @param {string} few @param {string} many */
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}

/** Locale-aware date. @param {number} ms @param {Intl.DateTimeFormatOptions} opts */
export function date(ms, opts) {
  return new Date(ms).toLocaleDateString(lang === 'ru' ? 'ru-RU' : 'en-GB', opts);
}
